"""Updates README badges based on coverage."""


def get_color(pct: float) -> str:
    """Return color for coverage percentage."""
    if pct >= 100:
        return "brightgreen"
    if pct >= 90:
        return "green"
    if pct >= 80:
        return "yellowgreen"
    if pct >= 70:
        return "yellow"
    if pct >= 60:
        return "orange"
    return "red"
